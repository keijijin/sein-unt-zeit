export function flattenFaqItems(): FaqItem[] {
  return FAQ_CATEGORIES.flatMap((c) => c.items)
}

export function findFaqItem(id: string): FaqItem | undefined {
  return flattenFaqItems().find((item) => item.id === id)
}

