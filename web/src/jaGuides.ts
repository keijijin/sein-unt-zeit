export function getJaGuide(section: Section): JaGuide {
  const titleJa = T[section.n] ?? `§${section.n}`
  const body = DEEP[section.n] ?? MID[section.n] ?? `（§${section.n}）${section.titleDe} に対応する箇所です。左のPDFで刷りページ ${section.bookPage} 付近を開き、ドイツ語の展開に追いながら、この日本語欄を「地図」として使ってください。`
  return { titleJa, body }
}

export function getSectionTitleJa(n: number): string {
  return T[n] ?? `§${n}`
}
